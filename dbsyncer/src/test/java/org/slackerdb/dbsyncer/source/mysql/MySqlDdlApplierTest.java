package org.slackerdb.dbsyncer.source.mysql;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.slackerdb.dbsyncer.model.TxPosition;
import org.slackerdb.dbsyncer.model.SourceTable;
import org.slackerdb.dbsyncer.state.SyncStateStore;
import org.slackerdb.dbsyncer.target.DuckDbHost;
import org.slackerdb.dbsyncer.target.DuckDbTarget;
import org.slackerdb.dbsyncer.target.DuckDbWriter;
import org.slackerdb.dbsyncer.model.TableMapping;
import org.slackerdb.dbsyncer.model.TargetTable;
import org.slf4j.LoggerFactory;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * MySQL DDL 解析/应用的单元测试：不需要真实 MySQL，目标用内存 DuckDB。
 *
 * <p>覆盖 binlog 里真实出现过的边界：服务端追加的 {@code /* generated by server *}{@code /} 注释、
 * DDL 与检查点同事务提交（曾在单写线程里自锁）、列/表重命名。</p>
 */
class MySqlDdlApplierTest {

    private Connection connection;
    private DuckDbTarget target;
    private DuckDbWriter writer;
    private MySqlDdlApplier applier;
    private final List<TableMapping> mappingList = new ArrayList<>();
    private final Map<String, TableMapping> mappings = new LinkedHashMap<>();

    @BeforeEach
    void setUp() throws Exception {
        connection = DriverManager.getConnection("jdbc:duckdb:");
        SyncStateStore stateStore = new SyncStateStore(connection, "memory");
        stateStore.initialize();
        DuckDbHost host = new DuckDbHost() {
            @Override
            public Connection duplicate() {
                return connection;
            }

            @Override
            public String catalog() {
                return "memory";
            }
        };
        this.target = new DuckDbTarget(host, LoggerFactory.getLogger(MySqlDdlApplierTest.class));
        this.writer = new DuckDbWriter(target, stateStore,
                LoggerFactory.getLogger(MySqlDdlApplierTest.class));
        this.applier = new MySqlDdlApplier(mappingList, mappings, writer,
                (schema, table) -> {
                    if (!table.startsWith("orders")) {
                        return null;
                    }
                    return mapping(schema, table);
                },
                LoggerFactory.getLogger(MySqlDdlApplierTest.class));
        TableMapping mapping = mapping("db", "orders");
        mappingList.add(mapping);
        mappings.put(mapping.sourceKey(), mapping);
        writer.prepare(List.of(mapping));
    }

    @AfterEach
    void tearDown() {
        target.close();
    }

    @Test
    @Timeout(30)
    void createTableInsideDdlTransactionDoesNotDeadlock() throws Exception {
        applier.applyAtomically("db", "CREATE TABLE db.orders_new (id BIGINT PRIMARY KEY, name VARCHAR(64))",
                "job1", TxPosition.mysql("binlog.000001", 100));

        assertTrue(tableExists("orders_new"));
        assertNotNull(mappings.get("db.orders_new"));
        assertEquals(100, stateStoreCheckpointPosition());
    }

    @Test
    void dropTableIgnoresServerGeneratedComment() throws Exception {
        applier.applyAtomically("db", "CREATE TABLE db.orders_new (id BIGINT PRIMARY KEY)",
                "job1", TxPosition.mysql("binlog.000001", 100));

        // MySQL 8 在 binlog 里给 DROP TABLE 追加注释，之前会把最后一个标识符污染成
        // "orders_new /* generated by server */"，于是被当成未映射表静默跳过。
        applier.apply("db", "DROP TABLE `db`.`orders_new` /* generated by server */");

        assertFalse(tableExists("orders_new"));
        assertNull(mappings.get("db.orders_new"));
    }

    @Test
    void alterAddColumnAndTruncateAndRename() throws Exception {
        applier.apply("db", "ALTER TABLE db.orders ADD COLUMN extra VARCHAR(32) NOT NULL");
        assertTrue(columnExists("orders", "extra"));

        try (Statement statement = connection.createStatement()) {
            statement.execute("INSERT INTO \"memory\".\"sync\".\"orders\" (id, name, extra)"
                    + " VALUES (1, 'a', 'x')");
        }
        applier.apply("db", "TRUNCATE TABLE db.orders");
        assertEquals(0, countRows("orders"));

        // 多语句 DDL：重命名列 + 类型变更（DuckDB 不允许改主键列类型，所以只动非主键列）
        applier.apply("db", "ALTER TABLE db.orders CHANGE COLUMN name title VARCHAR(128),"
                + " MODIFY title VARCHAR(200)");
        assertTrue(columnExists("orders", "title"));
        assertFalse(columnExists("orders", "name"));
        assertNull(mappings.get("db.orders").source().column("name"));
        assertNotNull(mappings.get("db.orders").source().column("title"));

        // 表重命名：目标表跟着改
        applier.apply("db", "RENAME TABLE db.orders TO db.orders_renamed");
        assertTrue(tableExists("orders_renamed"));
        assertFalse(tableExists("orders"));
        assertNotNull(mappings.get("db.orders_renamed"));
    }

    @Test
    void addColumnAfterKeepsSourceColumnOrder() throws Exception {
        applier.apply("db", "ALTER TABLE db.orders ADD COLUMN mid VARCHAR(16) AFTER id");
        assertEquals(List.of("id", "mid", "name"), sourceColumns("orders"));
        assertTrue(columnExists("orders", "mid"));

        // MODIFY ... AFTER 也要搬动位置
        applier.apply("db", "ALTER TABLE db.orders MODIFY mid VARCHAR(32) AFTER name");
        assertEquals(List.of("id", "name", "mid"), sourceColumns("orders"));

        // CHANGE ... FIRST：改名 + 换类型 + 挪到最前
        applier.apply("db", "ALTER TABLE db.orders CHANGE COLUMN name title VARCHAR(64) FIRST");
        assertEquals(List.of("title", "id", "mid"), sourceColumns("orders"));
        assertTrue(columnExists("orders", "title"));
        assertFalse(columnExists("orders", "name"));

        // 没有位置子句时保持追加语义
        applier.apply("db", "ALTER TABLE db.orders ADD COLUMN tail INT");
        assertEquals(List.of("title", "id", "mid", "tail"), sourceColumns("orders"));
    }

    @Test
    void unsupportedClauseOnMappedTableStillFails() {
        // 无关语句忽略，但"命中映射表 + 无法翻译的子句"仍必须报错（作业暂停而不是静默漂移）。
        assertThrows(UnsupportedOperationException.class, () -> applier.apply("db",
                "ALTER TABLE db.orders PARTITION BY HASH(id)"));
    }

    @Test
    void ignoresNonTableDdl() throws Exception {
        applier.apply("db", "CREATE INDEX idx_name ON db.orders (name)");
        applier.apply("db", "DROP VIEW IF EXISTS db.v");
        applier.apply("db", "CREATE DATABASE other");
        // 同实例里别的业务对象级 DDL 不能把同步作业卡停（曾经会抛 UnsupportedOperationException）
        applier.apply("db", "CREATE USER 'someone'@'%' IDENTIFIED BY 'x'");
        applier.apply("db", "ALTER USER 'someone'@'%' IDENTIFIED BY 'y'");
        applier.apply("db", "DROP USER 'someone'@'%'");
        applier.apply("db", "CREATE ROLE r1");
        applier.apply("db", "CREATE TABLESPACE ts ADD DATAFILE 'ts.ibd'");
        applier.apply("db", "ALTER INSTANCE ROTATE INNODB MASTER KEY");
        applier.apply("db", "SOME FUTURE STATEMENT");
        assertEquals(1, mappingList.size());
        assertEquals(2, mappingList.get(0).source().columns.size(), "非表 DDL 不应改动映射");
    }

    // ------------------------------------------------------------------ helpers

    private List<String> sourceColumns(String table) {
        return mappings.get("db." + table).source().columns.stream()
                .map(column -> column.name)
                .toList();
    }

    private static TableMapping mapping(String schema, String table) {
        SourceTable source = new SourceTable(schema, table, "mysql");
        source.columns.add(new SourceTable.SourceColumn("id", "bigint", java.sql.Types.BIGINT, 0, 0));
        source.columns.add(new SourceTable.SourceColumn("name", "varchar", java.sql.Types.VARCHAR, 64, 0));
        source.primaryKey.add("id");
        TargetTable targetTable = new TargetTable("memory", "sync", table);
        targetTable.add(new TargetTable.TargetColumn("id", "BIGINT", "id", null));
        targetTable.add(new TargetTable.TargetColumn("name", "VARCHAR", "name", null));
        targetTable.primaryKey.add("id");
        return new TableMapping(source, targetTable, "job1");
    }

    private boolean tableExists(String table) throws SQLException {
        return count("SELECT count(*) FROM information_schema.tables"
                + " WHERE table_catalog='memory' AND table_schema='sync' AND table_name='" + table + "'") > 0;
    }

    private boolean columnExists(String table, String column) throws SQLException {
        return count("SELECT count(*) FROM information_schema.columns"
                + " WHERE table_schema='sync' AND table_name='" + table
                + "' AND column_name='" + column + "'") > 0;
    }

    private int countRows(String table) throws SQLException {
        return count("SELECT count(*) FROM \"memory\".\"sync\".\"" + table + "\"");
    }

    private long stateStoreCheckpointPosition() throws SQLException {
        try (Statement statement = connection.createStatement();
             ResultSet rs = statement.executeQuery(
                     "SELECT binlog_pos FROM \"memory\".sysaux.v$dbsync_checkpoint WHERE job_name='job1'")) {
            return rs.next() ? rs.getLong(1) : 0;
        }
    }

    private int count(String sql) throws SQLException {
        try (Statement statement = connection.createStatement();
             ResultSet rs = statement.executeQuery(sql)) {
            return rs.next() ? rs.getInt(1) : 0;
        }
    }
}
